# Packed 5-bit exponents: check *before* addition, not merely after decoding (which masks a carry).
def checked_kernel(p):
 d=len(p['lo']);oldmul=G.mul;oldsplit=G.split;oldassemble=G.assemble
 def shape(poly):
  if any(type(k)!=int or k<0 or k>>(5*d) for k in poly):raise ValueError('polynomial exponent outside chart')
  return tuple(max(((k>>(5*i))&31 for k in poly),default=0) for i in range(d))
 def mul(a,b):
  aa,bb=shape(a),shape(b)
  if any(x+y>31 for x,y in zip(aa,bb)):raise ValueError('packed exponent overflow before multiplication')
  r=oldmul(a,b);shape(r);return r
 def split(poly,axis,sign):
  if type(axis)!=int or not 0<=axis<d:raise ValueError('inner split axis')
  r=oldsplit(poly,axis,sign);shape(r);return r
 def assembly(*args,**kwargs):
  r=oldassemble(*args,**kwargs)
  for a in r[0]+list(r[1:3]):shape(a)
  return r
 def inner(t,depth=0):
  if depth>12 or not isinstance(t,dict):raise ValueError('inner tree depth')
  if set(t)=={'mu'}:return 1
  if set(t)!={'axis','left','right'} or type(t['axis'])!=int or not 0<=t['axis']<d:raise ValueError('inner split structure')
  n=inner(t['left'],depth+1)+inner(t['right'],depth+1)
  if n>64:raise ValueError('inner split leaf cap')
  return n
 inner(p['tree'])
 G.mul,G.split,G.assemble=mul,split,assembly
 try:return G.replay(p)
 finally:G.mul,G.split,G.assemble=oldmul,oldsplit,oldassemble

def lg_bound(t,w,supp=False,cap=64):
 dim=4 if t['chart'].startswith('q') else 6
 if len(t['lo'])!=dim or len(t['hi'])!=dim or t['chart'] not in ('near','std','E2','E3','qstd','qE2','qE3'):raise ValueError('chart dimension')
 def walk(w,lo,hi,depth):
  if depth>12:raise ValueError('outer split depth')
  if set(w)=={'lg'}:
   p=w['lg'];n=p['N']
   if 'vertices' in p or p['chart']!=t['chart'] or p['j']!=t['j'] or type(n)!=int or not 1<=n<=12 or (not supp and n!=t['N']) or Q(p['L'])<Q(t['L']) or len(p['lo'])!=dim or len(p['hi'])!=dim or list(map(Q,p['lo']))!=list(map(Q,lo)) or list(map(Q,p['hi']))!=list(map(Q,hi)):raise ValueError('LG geometry / degree / target binding')
   if len(p['u']) not in (1,dim+1) or len(p['chi'])!=len(p['u']):raise ValueError('LG family size')
   if not checked_kernel(p):raise ValueError('LG exact replay')
   return 1
  if set(w)!={'axis','left','right'} or type(w['axis'])!=int or not 0<=w['axis']<dim:raise ValueError('outer split structure')
  a,b=P.mid_split(lo,hi,w['axis']);n=walk(w['left'],*a,depth+1)+walk(w['right'],*b,depth+1)
  if n>cap:raise ValueError('outer leaf cap')
  return n
 return walk(w,t['lo'],t['hi'],0)<=cap

def discrete_bound(t,w,cap):
 # identical direct mathematical routes, new outer budget, no search acceptance by status alone.
 def rec(w,lo,hi,dep):
  if dep>8:raise ValueError('discrete tree depth')
  if set(w)=={'leaf'}:
   p=P.q_direct(t,lo,hi,w['leaf']) if t['stage']=='q_other' else P.label_direct(t,lo,hi,Q(t.get('table','0')),w['leaf'])
   if p is None or p!=w['leaf']:raise ValueError('discrete witness')
   return 1,p['status']
  if set(w)!={'axis','left','right'} or type(w['axis'])!=int or not 0<=w['axis']<len(lo):raise ValueError('discrete split')
  a,b=P.mid_split(lo,hi,w['axis']);nl,sl=rec(w['left'],*a,dep+1);nr,sr=rec(w['right'],*b,dep+1)
  if nl+nr>cap:raise ValueError('discrete leaf cap')
  return nl+nr,'CONDITIONAL_TABLE' if 'CONDITIONAL_TABLE' in (sl,sr) else 'PROVED'
 return rec(w,t['lo'],t['hi'],0)[1]

def verify_one(args):
 t,r,supp,cap=args;st=time.monotonic();cpu=time.process_time()
 try:
  if r['id']!=t['id'] or r['task_sha256']!=D.identity(t):raise ValueError('frozen identity')
  s=r['status'];w=r.get('witness')
  if s in ('UNPROVED','ERROR'):
   if w is not None:raise ValueError('nonpassing record with witness')
   msg=str(r.get('reason','nonpassing record'))[:400]
  else:
   if w is None:raise ValueError('missing witness')
   actual=('PROVED' if lg_bound(t,w,supp,cap) else 'REJECT') if t['stage'] in D.LG else discrete_bound(t,w,cap)
   if actual!=s or actual not in ('PROVED','CONDITIONAL_TABLE'):raise ValueError('witness/status mismatch '+actual)
   msg=''
 except Exception as ex:s='REJECT';msg=repr(ex)[:400]
 return dict(id=t['id'],status=s,reason=msg,seconds=time.monotonic()-st,cpu=time.process_time()-cpu,rss_kib=resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)

