def bounded_map(pool,fn,items,work,a):
 it=iter(items);pending=[]
 while True:
  while len(pending)<2*len(pool._pool):
   try:x=next(it)
   except StopIteration:break
   pending.append((pool.apply_async(fn,(x,)),time.monotonic()))
  if not pending:break
  D.guard(work,a);now=time.monotonic();ready=[(v,ts) for v,ts in pending if v.ready()]
  if not ready:
   if any(now-ts>a.task_timeout for v,ts in pending):raise InterruptedError('worker timeout or died, no shard committed')
   time.sleep(.02);continue
  for v,ts in ready:pending.remove((v,ts));yield v.get()

